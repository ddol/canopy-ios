func ll(p s2.Point) string {
	l := s2.LatLngFromPoint(p)
	return fmt.Sprintf("(%.15f, %.15f)", l.Lat.Degrees(), l.Lng.Degrees())
}

func writeVectors() {
	out := os.Stdout
	fmt.Fprintln(out, "// Generated from github.com/golang/geo/s2 by scripts/s2-reference. Do not edit by hand.")
	fmt.Fprintln(out, "// swift-format-ignore-file")
	fmt.Fprintln(out, "")
	fmt.Fprintln(out, "struct S2Vector {")
	fmt.Fprintln(out, "    let name: String")
	fmt.Fprintln(out, "    let lat: Double")
	fmt.Fprintln(out, "    let lng: Double")
	fmt.Fprintln(out, "    let face: Int")
	fmt.Fprintln(out, "    let leafID: UInt64")
	fmt.Fprintln(out, "    let token16: String")
	fmt.Fprintln(out, "    let token19: String")
	fmt.Fprintln(out, "    let center16: (lat: Double, lng: Double)")
	fmt.Fprintln(out, "    let vertices16: [(lat: Double, lng: Double)]")
	fmt.Fprintln(out, "}")
	fmt.Fprintln(out, "")
	fmt.Fprintln(out, "let s2Vectors: [S2Vector] = [")
	for _, p := range points {
		id := s2.CellIDFromLatLng(s2.LatLngFromDegrees(p.lat, p.lng))
		c16 := s2.CellFromCellID(id.Parent(16))
		fmt.Fprintf(out, "    S2Vector(\n")
		fmt.Fprintf(out, "        name: %q, lat: %v, lng: %v, face: %d,\n", p.name, jsonNum(p.lat), jsonNum(p.lng), id.Face())
		fmt.Fprintf(out, "        leafID: 0x%016x, token16: %q, token19: %q,\n", uint64(id), id.Parent(16).ToToken(), id.Parent(19).ToToken())
		fmt.Fprintf(out, "        center16: %s,\n", ll(c16.Center()))
		fmt.Fprintf(out, "        vertices16: [%s, %s, %s, %s]\n", ll(c16.Vertex(0)), ll(c16.Vertex(1)), ll(c16.Vertex(2)), ll(c16.Vertex(3)))
		fmt.Fprintf(out, "    ),\n")
	}
	fmt.Fprintln(out, "]")
}

func jsonNum(f float64) string {
	b, _ := json.Marshal(f)
	s := string(b)
	return s
}

// MARK: cells (Fixtures/ggp/s2-cells.geojson)

type place struct {
	name     string
	lat, lng float64
	level    int
}

var places = []place{
	{"Conservatory of Flowers", 37.7720, -122.4602, 16},
	{"Conservatory of Flowers", 37.7720, -122.4602, 19},
	{"de Young Museum", 37.7715, -122.4687, 16},
	{"Stow Lake", 37.7699, -122.4757, 16},
	{"Spreckels Lake", 37.7706, -122.4945, 16},
	{"Dutch Windmill", 37.7704, -122.5090, 16},
	{"Panhandle at Masonic", 37.7718, -122.4462, 16},
}

func round9(v float64) float64 { return math.Round(v*1e9) / 1e9 }

func writeCells() {
	var features []map[string]any
	for _, p := range places {
		id := s2.CellIDFromLatLng(s2.LatLngFromDegrees(p.lat, p.lng)).Parent(p.level)
		cell := s2.CellFromCellID(id)
		var ring [][]float64
		for k := 0; k <= 4; k++ {
			ll := s2.LatLngFromPoint(cell.Vertex(k % 4))
			ring = append(ring, []float64{round9(ll.Lng.Degrees()), round9(ll.Lat.Degrees())})
		}
		kind := "tile"
		if p.level == 19 {
			kind = "chunk"
		}
		features = append(features, map[string]any{
			"type": "Feature",
			"id":   id.ToToken(),
			"geometry": map[string]any{
				"type":        "Polygon",
				"coordinates": [][][]float64{ring},
			},
			"properties": map[string]any{"token": id.ToToken(), "level": p.level, "kind": kind, "near": p.name},
		})
	}
	out := map[string]any{
		"type":        "FeatureCollection",
		"name":        "Sample S2 cells in Golden Gate Park",
		"description": "Gerardus tiles (S2 level 16) and a chunk (level 19). Corners from github.com/golang/geo/s2; generated by scripts/s2-reference.",
		"features":    features,
	}
	enc := json.NewEncoder(os.Stdout)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	enc.Encode(out)
}
